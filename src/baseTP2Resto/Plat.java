package baseTP2Resto;

public class Plat {
	
	private int id;
	private String nom;
	
    // Constructeur
    public Plat(String nom) {
        this.id = id;
        this.nom = nom;
    }
    
    // Getters
    public int getId() {
        return id;
    }

    public String getNom() {
        return nom;
    }
    
    //Setters
    public void setId(int id) {
        this.id = id;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

}
